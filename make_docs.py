"""Generate SRT, facts sheet, theme, storyboard and README."""
import json
from pathlib import Path
import scenes, engine

ROOT = Path(__file__).resolve().parent
T = json.loads((ROOT / "assets" / "timeline.json").read_text(encoding="utf-8"))
LINES = T["lines"]
INTRO = engine.INTRO

def ts(s):
    h = int(s // 3600); m = int((s % 3600) // 60); sec = s % 60
    return f"{h:02d}:{m:02d}:{sec:06.3f}".replace(".", ",")

# ------------------------------------------------------------------ SRT
srt = []
for L in LINES:
    if L["kind"] != "spoken": continue
    a, b = L["show_start"] + INTRO, L["show_end"] + INTRO
    txt = L["body"]
    if L["label"]: txt = L["label"] + ": " + txt
    srt.append(f"{len(srt)+1}\n{ts(a)} --> {ts(b)}\n{txt}\n")
(ROOT / "subtitles.srt").write_text("\n".join(srt), encoding="utf-8")

